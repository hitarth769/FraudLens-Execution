import type { CaseDetail, EvidenceItem, PatternType, Severity } from '../types'

let evCounter = 0
function ev(
  id: string,
  pattern: PatternType,
  type: string,
  title: string,
  observed: string,
  baseline: string,
  whyItMatters: string,
  severity: Severity,
  table: string,
  eventId: string,
  revealedAtStep: number,
  polarity: 'SUPPORTING' | 'CONTRADICTING' = 'SUPPORTING',
): EvidenceItem {
  evCounter += 1
  return {
    id,
    type,
    pattern,
    title,
    claim: title,
    observed,
    baseline,
    whyItMatters,
    severity,
    polarity,
    source: { table, eventId },
    revealedAtStep,
  }
}

